EXAMPLE_DIRS = ["examples/usyd-md"]


def examples_section(root: Path) -> str:
    """One bullet per institution example, built from the example's own values, so
    institution names live only in the example folder and in this generated page."""
    out = []
    for rel in EXAMPLE_DIRS:
        f = root / rel / "config.toml"
        if not f.is_file():
            continue
        with open(f, "rb") as fh:
            doc = tomllib.load(fh)
        inst = doc.get("institution", {})
        tiers = [t.get("label", "") for t in doc.get("tiers", {}).get("tier", [])]
        unit = f", with unit code `{inst['unit_code']}` as a label" if inst.get("unit_code") else ""
        out.append(
            f"- `{rel}/config.toml`: every institution key filled for {inst.get('name', rel)}"
            f"{unit}, dotted week numbering (block week and session), learning-outcome headings "
            f"that carry that number, and {len(tiers)} source tiers: "
            + "; ".join(tiers) + ". Public programme values only; replace its placeholder "
            "paths with your own. `" + rel + "/README.md` explains each value.")
    return "\n".join(out) + ("\n" if out else "")

TYPE_NAMES = {"string": "str", "integer": "int", "boolean": "bool", "number": "float"}
PATH_NOTE = {
    "config": "Path; relative to the config file's folder.",
    "curriculum": "Path; relative to `curriculum.root`.",
    "data": "Folder; relative to the data folder.",
}


def _shared(root: Path) -> Path:
    return root / "shared"


def _toml_value(v) -> str:
    text = tomlw.dumps({"k": v}).strip()
    return text.split("=", 1)[1].strip() if text.startswith("k =") else text


def _type(s: dict) -> str:
    t = s.get("type")
    if t == "array":
        it = s.get("items", {})
        if it.get("type") == "object":
            return "array of tables"
        return f"list[{TYPE_NAMES.get(it.get('type'), it.get('type', 'any'))}]"
    if t == "object":
        return "table"
    return TYPE_NAMES.get(t, str(t))


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _default_cell(key: str, value, style_keys: bool, have_style: bool) -> tuple[str, str | None]:
    if value is _NONE:
        if style_keys and not have_style:
            return "set in `shared/style.defaults.toml`", None
        return "", None
    rendered = _toml_value(value)
    if len(rendered) > 60 or "\n" in rendered:
        return "see below", rendered
    return f"`{_cell(rendered)}`", None


_NONE = object()


def _lookup(doc: dict, dotted: str):
    node = doc
    for part in dotted.split("."):
        if not isinstance(node, dict) or part not in node:
            return _NONE
        node = node[part]
    return node


def _meaning(s: dict) -> str:
    parts = [s.get("description", "").strip()]
    if "enum" in s and s.get("type") != "integer":
        parts.append("One of: " + ", ".join(f"`{e}`" for e in s["enum"]) + ".")
    if s.get("x-path") in PATH_NOTE:
        parts.append(PATH_NOTE[s["x-path"]])
    if s.get("x-regex"):
        parts.append("Must compile as a Python regular expression.")
    return _cell(" ".join(p for p in parts if p))


def _rows(prefix: str, s: dict, defaults: dict, out: list, blocks: list,
          style_keys: bool, have_style: bool) -> None:
    for k, sub in s.get("properties", {}).items():
        key = f"{prefix}{k}"
        if sub.get("type") == "object" and "properties" in sub:
            _rows(key + ".", sub, defaults, out, blocks, style_keys, have_style)
            continue
        dcell, block = _default_cell(key, _lookup(defaults, key), style_keys, have_style)
        out.append(f"| `{key}` | {_type(sub)} | {dcell} | {_meaning(sub)} |")
        if block is not None:
            blocks.append((key, block))
        items = sub.get("items", {})
        if sub.get("type") == "array" and items.get("type") == "object":
            for ik, isub in items.get("properties", {}).items():
                req = " Required." if ik in items.get("required", []) else ""
                idef = isub.get("default", _NONE)
                icell = f"`{_cell(_toml_value(idef))}`" if idef is not _NONE else ""
                out.append(f"| `{key}[].{ik}` | {_type(isub)} | {icell} | "
                           f"{_meaning(isub)}{req} |")


def render(root: Path) -> str:
    shared = _shared(root)
    schema = json.loads((shared / "schemas" / "config.schema.json").read_text(encoding="utf-8"))
    with open(shared / "config.defaults.toml", "rb") as fh:
        defaults = tomllib.load(fh)
    style_file = shared / "style.defaults.toml"
    have_style = style_file.is_file()
    if have_style:
        with open(style_file, "rb") as fh:
            for k, v in tomllib.load(fh).items():
                if isinstance(v, dict) and isinstance(defaults.get(k), dict):
                    defaults[k].update(v)
                else:
                    defaults[k] = v
    lines = [INTRO.replace("{examples}\n", examples_section(root))]
    for top, s in schema["properties"].items():
        style_keys = top in ("style", "fonts")
        lines.append(f"### `{top}`\n")
        if s.get("description"):
            lines.append(s["description"].strip() + "\n")
        rows: list[str] = ["| Key | Type | Default | Meaning |", "|---|---|---|---|"]
        blocks: list[tuple[str, str]] = []
        if s.get("type") == "object" and "properties" in s:
            _rows(f"{top}.", s, defaults, rows, blocks, style_keys, have_style)
        else:
            _rows("", {"properties": {top: s}}, defaults, rows, blocks, style_keys, have_style)
        lines.append("\n".join(rows) + "\n")
        for key, block in blocks:
            value = _lookup(defaults, key)
            if isinstance(value, list) and value and all(isinstance(x, dict) for x in value):
                parts = key.split(".")
                nested: dict = {}
                node = nested
                for p in parts[:-1]:
                    node = node.setdefault(p, {})
                node[parts[-1]] = value
                block = tomlw.dumps(nested).strip()
            else:
                block = f"{key.split('.')[-1]} = {block}"
            lines.append(f"Default for `{key}`:\n\n```toml\n{block}\n```\n")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when the file is out of date")
    ap.add_argument("--root", type=Path, default=REPO, help=argparse.SUPPRESS)
    a = ap.parse_args(argv)
    root = a.root.resolve()
    text = render(root)
    out = root / OUT
    if a.check:
        old = out.read_text(encoding="utf-8") if out.is_file() else ""
        if old != text:
            diff = list(difflib.unified_diff(old.splitlines(), text.splitlines(),
                                             f"{OUT} (on disk)", f"{OUT} (generated)", lineterm="",
                                             n=1))
            print(f"DRIFT {OUT} is out of date; run python3 tools/gen_config_docs.py")
            for line in diff[:40]:
                print(line)
            return 1
        print(f"ok {OUT} matches the generator")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
