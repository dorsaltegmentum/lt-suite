def glyph_names(font):
    cmap = font.getBestCmap()
    return {name: cp for cp, name in cmap.items()
            if (FIRST <= cp <= LAST and name.startswith("md-")) or name.startswith(SETS)}


def glyph(name):
    """The font's glyph name for an icon name: "pill" -> "md-pill"; "fae-lung" stays as it is."""
    return name if name.startswith(SETS) else "md-" + name


def key(name):
    return name.replace("-", "_") if name.startswith(SETS) else name


def extract(font, name):
    """The path data of an icon in the 24 x 24 MDI box (y down): an MDI glyph at MDI's own scale, any other
    set's glyph fitted (longer side FIT units, centred)."""
    gs = font.getGlyphSet()
    g = gs[glyph(name)]
    bp = BoundsPen(gs)
    g.draw(bp)
    x0, y0, x1, y1 = bp.bounds
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    s = GRID / UNITS_PER_GRID if not name.startswith(SETS) else FIT / max(x1 - x0, y1 - y0)
    pen = SVGPathPen(gs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    # x' = 12 + s (x - cx);  y' = 12 - s (y - cy)
    g.draw(TransformPen(pen, (s, 0, 0, -s, GRID / 2 - s * cx, GRID / 2 + s * cy)))
    return pen.getCommands(), (s * (x1 - x0), s * (y1 - y0))


def main(argv):
    ap = argparse.ArgumentParser(description="Extract MDI icons from the Nerd Font into icons.py")
    ap.add_argument("names", nargs="*", help="icon names without the md- prefix (default: NAMES)")
    ap.add_argument("--font", default=os.environ.get("NERD_FONT"),
                    help="a Nerd Fonts 3 font file (default: $NERD_FONT)")
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--preview", help="write a contact sheet SVG instead of icons.py")
    a = ap.parse_args(argv)
    if not a.font:
        raise SystemExit("extract_icons.py: give --font FILE or set NERD_FONT to a Nerd Fonts 3 font file")
    font = TTFont(a.font)
    have = glyph_names(font)
    names = a.names or NAMES
    missing = [n for n in names if glyph(n) not in have]
    if missing:
        raise SystemExit(f"not in {pathlib.Path(a.font).name}: {', '.join(missing)}")
    paths = {key(n): extract(font, n) for n in dict.fromkeys(names)}
    if a.preview:
        cols, cell = 8, 96
        rows = (len(paths) + cols - 1) // cols
        out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{cols * cell}" height="{rows * cell}" '
               f'viewBox="0 0 {cols * cell} {rows * cell}"><rect width="100%" height="100%" fill="#ffffff"/>']
        for i, (n, (d, _)) in enumerate(paths.items()):
            x, y = (i % cols) * cell, (i // cols) * cell
            out.append(f'<rect x="{x + 24}" y="{y + 8}" width="48" height="48" fill="none" stroke="#cccccc"/>')
            out.append(f'<path transform="translate({x + 24},{y + 8}) scale(2)" d="{d}" fill="#222222"/>')
            out.append(f'<text x="{x + 48}" y="{y + 76}" font-size="9" text-anchor="middle" font-family="sans-serif" '
                       f'fill="#222222">{n}</text>')
        out.append("</svg>")
        pathlib.Path(a.preview).write_text("\n".join(out))
        print(f"wrote {a.preview}: {len(paths)} icons")
        return
    ver = next((r.toUnicode() for r in font["name"].names if r.nameID == 5 and r.platformID == 3), "?")
    nerd = ver[ver.find("Nerd Fonts"):] if "Nerd Fonts" in ver else ver
    body = [HEADER.format(fontver=nerd.replace('"', "'"))]
    for n, (d, (w, h)) in paths.items():
        body.append(f'    "{n}": "{d}",  # {w:.1f} x {h:.1f}\n')
    body.append("}\n")
    pathlib.Path(a.out).write_text("".join(body))
    print(f"wrote {a.out}: {len(paths)} icons")


if __name__ == "__main__":
    main(sys.argv[1:])
