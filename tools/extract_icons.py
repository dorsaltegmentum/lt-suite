"""Extract Material Design Icons from a Nerd Font into the diagram engine's icons.py (a maintainer tool).

    python3 tools/extract_icons.py --font FONT.ttf       # the icons the engine uses (NAMES) -> engine/icons.py
    NERD_FONT=FONT.ttf python3 tools/extract_icons.py    # the same, the font from the environment
    python3 tools/extract_icons.py --font FONT.ttf --preview sheet.svg pill cog bacteria ...   # a contact sheet

FONT is any installed Nerd Fonts 3 patched font (or the Symbols Only font). No network: the icons come
from a font already on the machine. Nerd Fonts (MIT) ships the
Pictogrammers Material Design Icons (Apache License 2.0) in the range U+F0001..U+F1AF0, with
glyph names "md-<name>" (md-pill, md-heart_pulse ...). Some organ icons require other sets.

How a glyph becomes an SVG path: Nerd Fonts' patcher scales the whole MDI set by one factor
(the 24-unit MDI grid becomes 1000 font units) and centres each glyph's bounding box on a fixed
point, so the icons keep their relative sizes. extract() maps the glyph back to the 24 x 24 MDI
box: the bounding-box centre goes to (12, 12), the scale is 24 / 1000, and y is flipped (font y
runs up, SVG y down). The path is drawn with fontTools' SVGPathPen through a TransformPen, so the
quadratic outlines of the TrueType glyphs survive exactly (Q commands), rounded to 0.01 unit.

To add an icon: add its name to NAMES (or the case's own list), run this script, and check it on
a --preview sheet. Keep icons.py to what is used plus a few spares.

Other sets: any installed font or icon set can supply icons. A name with a Nerd Fonts set prefix
is taken from that set as it is, e.g. "fae-lung" (Font Awesome Extension),
"fa-lungs" (Font Awesome 6 Free), "oct-alert" (Octicons), "cod-pulse" (Codicons),
"weather-thermometer". Those sets are not on MDI's grid, so each glyph is fitted into the 24-unit box (its
longer side 20 units, centred), and its icons.py key is the name with "-" as "_" ("fae_lung").
Each set keeps its own licence: Font Awesome Free icons are CC BY 4.0, so a new fa_ key needs its
attribution in THIRD_PARTY_NOTICES.md and an SPDX line in the generated header.
"""
import argparse, os, pathlib, sys

from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

OUT = pathlib.Path(__file__).resolve().parent.parent / "skills" / "mechanistic-diagram" / "engine" / "icons.py"
FIRST, LAST = 0xF0001, 0xF1AF0          # the Material Design Icons block in Nerd Fonts 3
GRID = 24.0                              # MDI's design grid
SETS = ("fae-", "fa-", "oct-", "cod-", "weather-", "dev-", "seti-")   # other Nerd Fonts sets, by glyph-name prefix
FIT = 20.0                               # a glyph from another set fills this much of the 24-unit box
UNITS_PER_GRID = 1000.0                  # Nerd Fonts maps the 24-unit grid onto 1000 font units

NAMES = [
    # role glyphs (themes.ROLE_ICON)
    "dice_5", "cog", "human", "stethoscope", "test_tube", "clipboard_pulse", "medical_bag",
    # stage glyphs (case.json "stages")
    "diamond_stone", "lightning_bolt", "pipe_valve", "eye", "bacteria", "bullseye_arrow",
    "close_circle_outline", "pill", "heart_pulse", "account_group",
    # flags (themes.FLAGS)
    "alert", "alarm_light", "star",
    # the anatomy inset's header glyph (decor.INSET_ICON)
    "map_marker",
    # spares for other cases
    "stomach", "water", "thermometer", "needle", "iv_bag", "flask", "microscope", "dna", "bone", "fire",
    "biohazard", "shield_alert", "heart_broken", "gender_female", "clock_outline", "arrow_up_bold",
    "arrow_down_bold", "chevron_right", "lungs", "brain", "pipe", "pipe_disconnected", "pipe_leak", "virus",
    "hospital_box_outline", "food", "dice_multiple", "trending_up",
    # organs MDI lacks, from Font Awesome Extension
    "fae-liver", "fae-lung", "fae-stomach", "fae-real_heart", "fae-brain",
]

